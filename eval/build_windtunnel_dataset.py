ROOT = Path(__file__).resolve().parents[1]


def normalize(text: str) -> str:
    return re.sub(r"\s+", "", text)


def load_corpus():
    docs = {}
    for dirname, kind in (("json", "statute"), ("json_cases", "case")):
        for path in sorted((ROOT / "knowledge_data" / dirname).glob("*.json")):
            data = json.loads(path.read_text(encoding="utf-8-sig"))
            did = str(data["doc_id"])
            if did in docs:
                raise ValueError(f"Duplicate doc_id {did}")
            docs[did] = {**data, "doc_type": kind, "json_path": str(path.relative_to(ROOT))}
    return docs


def build_catalog():
    docs = load_corpus()
    items = []
    for did, doc in sorted(docs.items()):
        items.append({"doc_id": did, "doc_type": doc["doc_type"], "title": doc["title"],
                      "json_path": doc["json_path"], "source_path": doc.get("source_path"),
                      "parent_ids": [p["parent_id"] for p in doc["parents"]],
                      "parents": [{"parent_id": p["parent_id"], "title_path": p.get("title_path", ""),
                                   "first_line": p["text"].splitlines()[0][:180],
                                   "chars": len(p["text"]),
                                   "text_sha256": hashlib.sha256(p["text"].encode()).hexdigest()}
                                  for p in doc["parents"]]})
    path = ROOT / "eval/kb_catalog.json"
    path.write_text(json.dumps({"documents": items, "counts": {
        "statute_documents": sum(d["doc_type"] == "statute" for d in items),
        "case_documents": sum(d["doc_type"] == "case" for d in items),
        "parents": sum(len(d["parent_ids"]) for d in items)}}, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Catalog: {len(items)} documents")
    return docs


