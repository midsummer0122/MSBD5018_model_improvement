def validate_queries(rows, docs):
    assert len(rows)==60
    assert Counter(r["query_type"] for r in rows)=={"法律咨询":24,"法条解释":18,"程序咨询":12,"案例检索":6}
    assert Counter(r["split"] for r in rows)=={"dev":12,"test":48}
    assert sum(bool(r["relevant_case_doc_ids"]) for r in rows)==24
    assert len({r["query_id"] for r in rows})==len({r["query"] for r in rows})==60
    # Case families in dev are kept out of test, to avoid copied case questions across splits.
    case_sets={s:{d for r in rows if r["split"]==s for d in r["relevant_case_doc_ids"]} for s in ("dev","test")}
    assert not case_sets["dev"] & case_sets["test"]
    checks=0
    parents={p["parent_id"]:p for d in docs.values() for p in d["parents"]}
    for r in rows:
        assert set(r["relevant_doc_ids"])==set(r["relevant_statute_doc_ids"]+r["relevant_case_doc_ids"])
        assert {p.split('_')[0] for p in r["relevant_parent_ids"]}==set(r["relevant_doc_ids"])
        for c in r["source_checks"]:
            assert normalize(c["quote"]) in normalize(parents[c["parent_id"]]["text"])
            checks+=1
    return {"queries":60,"splits":dict(Counter(r['split'] for r in rows)),
            "intents":dict(Counter(r['query_type'] for r in rows)),"case_labeled_queries":24,
            "statute_only_queries":36,"verified_source_quotes":checks,
            "annotation_method":"Source-first manual scenario/rule design + literal parent quotation checks; no retrieval used",
            "limitations":["Curated binary positives are not exhaustive relevance judgments for all 302 documents.",
                           "Parent-level labels describe rule-bearing original parents; evidence text may be truncated.",
                           "No independent second human annotation; authoring and source checking were performed by the same assistant."]}


